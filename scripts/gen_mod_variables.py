#!/usr/bin/env python3
"""Generate src/spendlens/mod/finops/variables.pp from spendlens.config.SizingStandards.

Config field name == mod variable name, so adding a threshold is: add a field, run this script,
use var.<name> / a param in a control.

    python scripts/gen_mod_variables.py          # write
    python scripts/gen_mod_variables.py --check  # exit 1 if stale (CI / tests)
"""

from __future__ import annotations

import json
import sys
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from spendlens.config import SizingStandards

OUT = ROOT / "src" / "spendlens" / "mod" / "finops" / "variables.pp"
HEADER = "// GENERATED by scripts/gen_mod_variables.py from spendlens.config.SizingStandards. Do not edit.\n"


def hcl_type(ann: object) -> str:
    origin = typing.get_origin(ann)
    args = typing.get_args(ann)
    if ann is bool:
        return "bool"
    if ann in (int, float):
        return "number"
    if ann is str:
        return "string"
    if origin is list:
        return f"list({hcl_type(args[0])})"
    if origin is dict:
        return f"map({hcl_type(args[1])})"
    raise TypeError(f"Unsupported field type {ann!r}")


def hcl_default(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{json.dumps(k)} = {hcl_default(x)}" for k, x in v.items()) + "}"
    return json.dumps(v)


def render() -> str:
    defaults = SizingStandards()
    blocks = [HEADER]
    for name, field in SizingStandards.model_fields.items():
        blocks.append(
            f'variable "{name}" {{\n'
            f"  type        = {hcl_type(field.annotation)}\n"
            f'  description = "finops.yaml sizing.{name}"\n'
            f"  default     = {hcl_default(getattr(defaults, name))}\n"
            f"}}\n"
        )
    blocks.append(
        'variable "environment_tag" {\n'
        "  type        = string\n"
        '  description = "finops.yaml tagging.environment_tag: tag key used by *_by_env policies"\n'
        '  default     = "Environment"\n'
        "}\n"
    )
    return "\n".join(blocks)


def main() -> int:
    text = render()
    current = OUT.read_text() if OUT.exists() else None
    if "--check" in sys.argv:
        if current != text:
            print(f"Stale: {OUT}")
            return 1
        print("Up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(SizingStandards.model_fields) + 1} variables)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
