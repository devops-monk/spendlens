#!/usr/bin/env python3
"""Generate Powerpipe tag controls/benchmarks from spendlens.features.tags_catalog.

    python scripts/gen_tag_controls.py          # write src/spendlens/mod/tags/*.pp
    python scripts/gen_tag_controls.py --check  # exit 1 if generated files are stale (CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from spendlens.features.tags_catalog import TAGGABLE_RESOURCES
from spendlens.features.tags_checks import TAG_CHECKS

OUT_DIR = ROOT / "src" / "spendlens" / "mod" / "tags"
HEADER = "// GENERATED by scripts/gen_tag_controls.py from features/tags_catalog.py. Do not edit.\n"


def render_check(check: str) -> str:
    spec = TAG_CHECKS[check]
    parts = [HEADER]
    names = []
    for slug, (table, plural) in TAGGABLE_RESOURCES.items():
        name = f"tags_{check}_{slug}"
        names.append(name)
        param = (
            f'\n  param "{spec.param}" {{\n    default = var.{spec.param}\n  }}\n' if spec.param else "\n"
        )
        parts.append(
            f'control "{name}" {{\n'
            f'  title       = "{plural} {spec.title_suffix}"\n'
            f'  description = "{spec.description.format(plural=plural)}"\n'
            f'  severity    = "{spec.severity}"\n'
            f'  sql         = replace(local.tags_{check}_sql, "__TABLE_NAME__", "{table}")\n'
            f'  tags = {{\n'
            f'    spendlens_check = "tags_{check}"\n'
            f'    resource_type   = "{slug}"\n'
            f'  }}'
            f"{param}"
            f"}}\n"
        )
    children = "".join(f"    control.{n},\n" for n in names)
    parts.append(
        f'benchmark "tags_{check}" {{\n'
        f'  title       = "{spec.benchmark_title}"\n'
        f'  description = "{spec.benchmark_description}"\n'
        f"  children = [\n{children}  ]\n"
        f"}}\n"
    )
    return "\n".join(parts)


def render_parent() -> str:
    children = "".join(f"    benchmark.tags_{c},\n" for c in TAG_CHECKS)
    return (
        HEADER
        + '\nbenchmark "tags" {\n'
        + '  title       = "Tag compliance"\n'
        + '  description = "Company tagging policy: mandatory, untagged, prohibited, limit and expected values."\n'
        + f"  children = [\n{children}  ]\n}}\n"
    )


def outputs() -> dict[Path, str]:
    files = {OUT_DIR / f"controls_{c}.pp": render_check(c) for c in TAG_CHECKS}
    files[OUT_DIR / "benchmark.pp"] = render_parent()
    return files


def main() -> int:
    check_only = "--check" in sys.argv
    stale = []
    for path, text in outputs().items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not check_only:
                path.write_text(text)
    if check_only and stale:
        print("Stale generated files:", *map(str, stale), sep="\n  ")
        return 1
    print(("Up to date" if not stale else f"Wrote {len(stale)} file(s)") + f" ({len(TAGGABLE_RESOURCES)} resource types)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
