#!/usr/bin/env python3
"""Generate docs/controls.md (catalog of rightsize/waste controls) from the bundled mod.

    python scripts/gen_control_docs.py [--check]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from spendlens.features.savings import ESTIMATORS
from spendlens.features.tags_catalog import TAGGABLE_RESOURCES
from spendlens.features.tags_checks import TAG_CHECKS
from spendlens.powerpipe import bundled_mod_dir, mod_controls

OUT = ROOT / "docs" / "controls.md"
PARAM_RE = re.compile(r'param\s+"([a-z0-9_]+)"')


def params_by_control() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for f in (bundled_mod_dir() / "finops").glob("*.pp"):
        for name, body in re.findall(r'^control\s+"([a-z0-9_]+)"\s*\{(.*?)^\}', f.read_text(), re.MULTILINE | re.DOTALL):
            out[name] = [p for p in PARAM_RE.findall(body) if p != "environment_tag"]
    return out


def render() -> str:
    idx = mod_controls(bundled_mod_dir())
    params = params_by_control()
    lines = ["<!-- GENERATED by scripts/gen_control_docs.py. Do not edit. -->", "# spendlens controls", ""]
    for check, heading in (("rightsize", "Rightsizing and company standards (`spendlens rightsize`)"),
                           ("waste", "Idle and orphaned resources (`spendlens waste`)")):
        rows = sorted((v.get("service", ""), k, v) for k, v in idx.items() if v.get("spendlens_check") == check)
        lines += [f"## {heading}", "", f"{len(rows)} controls.", "",
                  "| Service | Control | What it checks | Parameters (`sizing.*`) | $ estimate |",
                  "|---|---|---|---|---|"]
        for service, name, v in rows:
            ps = ", ".join(f"`{p}`" for p in params.get(name, [])) or "-"
            lines.append(f"| {service} | `{name}` | {v.get('title', '')} | {ps} | {'yes' if name in ESTIMATORS else '-'} |")
        lines.append("")
    lines += ["## Tag compliance (`spendlens tags`)", "",
              (f"{len(TAG_CHECKS)} checks x {len(TAGGABLE_RESOURCES)} resource types = "
              f"{len(TAG_CHECKS) * len(TAGGABLE_RESOURCES)} controls, named `tags_<check>_<resource_type>`."), "",
              "| Check | Parameter |", "|---|---|"]
    lines += [f"| {k} | {f'`tagging.*` -> `{v.param}`' if v.param else '-'} |" for k, v in TAG_CHECKS.items()]
    lines += ["", "Resource types: " + ", ".join(f"`{k}`" for k in TAGGABLE_RESOURCES), ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("Up to date" if ok else f"Stale: {OUT}")
        return 0 if ok else 1
    OUT.write_text(text)
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
